/**
 * Un numero di gesto (UUID versione 4), anche dove il browser non ha `crypto.randomUUID`: una pagina servita senza https (il server dell'ufficio,
 * `http://192.168.1.20`) ha solo `crypto.getRandomValues`, e un browser molto vecchio nemmeno quello. Il server conta una volta un numero che arriva due volte.
 */
export function nuovoNumero(): string {
    const c = globalThis.crypto as Crypto | undefined;
    if (c && typeof c.randomUUID === 'function') return c.randomUUID();
    const b = new Uint8Array(16);
    if (c && typeof c.getRandomValues === 'function') c.getRandomValues(b);
    else for (let i = 0; i < 16; i++) b[i] = Math.floor(Math.random() * 256);
    b[6] = (b[6] & 0x0f) | 0x40;
    b[8] = (b[8] & 0x3f) | 0x80;
    const h = [...b].map((x) => x.toString(16).padStart(2, '0')).join('');

    return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
